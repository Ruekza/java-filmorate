CREATE TABLE IF NOT EXISTS films (
film_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name varchar(255) NOT NULL,
description varchar(200) NOT NULL,
release_date date NOT NULL,
duration INTEGER NOT NULL,
CONSTRAINT date_valid CHECK (release_date > '1895-12-28')
);

CREATE TABLE IF NOT EXISTS users (
user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
email varchar(100) NOT NULL UNIQUE,
login varchar(100) NOT NULL,
name varchar(255),
birthday date NOT NULL,
CHECK (name IS NOT NULL OR (name = login))
);

CREATE TABLE IF NOT EXISTS genres (
genre_id BIGINT PRIMARY KEY,
name varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS films_genres (
--id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
film_id BIGINT, --REFERENCES films ON DELETE CASCADE,
genre_id BIGINT, --REFERENCES genres,
PRIMARY KEY (film_id, genre_id),
FOREIGN KEY (film_id) REFERENCES films ON DELETE CASCADE,
FOREIGN KEY (genre_id) REFERENCES genres
);

CREATE TABLE IF NOT EXISTS mpa (
mpa_id BIGINT PRIMARY KEY,
name varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS films_mpa (
film_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
mpa_id BIGINT REFERENCES mpa,
FOREIGN KEY (film_id) REFERENCES films(film_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS likes (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
film_id BIGINT REFERENCES films ON DELETE CASCADE,
user_id BIGINT REFERENCES users ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS statuses (
id BIGINT PRIMARY KEY,
name varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS friends (
    user1_id BIGINT,
    user2_id BIGINT,
    status_id BIGINT DEFAULT 1,
    PRIMARY KEY (user1_id, user2_id),
    FOREIGN KEY (user1_id) REFERENCES users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (user2_id) REFERENCES users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (status_id) REFERENCES statuses(id)
);